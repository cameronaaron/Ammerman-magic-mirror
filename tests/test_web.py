from __future__ import annotations

import pytest

from magic_mirror.config import Settings, Source
from magic_mirror.web.storage import Storage, StorageError

_GENOME = (
    b"# This data file generated by 23andMe\n"
    b" rsid\tchromosome\tposition\tgenotype\n"
    b"rs4988235\t2\t136608646\tAA\n"
    b"rs1815739\t11\t66560624\tCC\n"
)


# --------------------------------------------------------------------------- #
# Storage layer (no FastAPI needed)
# --------------------------------------------------------------------------- #
def test_create_user_and_authenticate(tmp_path):
    store = Storage(tmp_path)
    uid = store.create_user("Ada", "hunter2")
    assert store.username_for(uid) == "ada"                 # normalised
    assert store.authenticate("ada", "hunter2") == uid
    assert store.authenticate("ada", "wrong") is None
    assert store.authenticate("nobody", "x") is None


def test_duplicate_username_rejected(tmp_path):
    store = Storage(tmp_path)
    store.create_user("ada", "pw")
    with pytest.raises(StorageError):
        store.create_user("ADA", "other")


def test_sessions_round_trip(tmp_path):
    store = Storage(tmp_path)
    uid = store.create_user("ada", "pw")
    token = store.create_session(uid)
    assert store.user_for_token(token) == uid
    assert store.user_for_token("garbage") is None
    assert store.user_for_token("") is None


def test_save_genome_validates_and_scopes(tmp_path):
    store = Storage(tmp_path)
    a = store.create_user("a", "pw")
    b = store.create_user("b", "pw")
    rec = store.save_genome(a, "genome.txt", _GENOME)
    assert rec.markers == 2 and rec.stored_path.exists()

    # Owner sees it; the other user cannot.
    assert store.get_genome(a, rec.id) is not None
    assert store.get_genome(b, rec.id) is None
    assert [g.id for g in store.list_genomes(a)] == [rec.id]

    with pytest.raises(StorageError):
        store.save_genome(a, "notes.txt", b"just some prose, not a genome\n")


# --------------------------------------------------------------------------- #
# HTTP API (skipped if FastAPI isn't installed)
# --------------------------------------------------------------------------- #
def _client(tmp_path):
    fastapi = pytest.importorskip("fastapi")
    from fastapi.testclient import TestClient

    from magic_mirror.web import create_app

    settings = Settings(source=Source.CSV, genome_from_usb=False)
    return TestClient(create_app(settings, data_dir=tmp_path)), fastapi


def test_full_upload_and_traits_flow(tmp_path):
    client, _ = _client(tmp_path)

    assert client.post("/api/register", json={"username": "ada", "password": "pw"}).status_code == 201
    token = client.post("/api/login", json={"username": "ada", "password": "pw"}).json()["token"]
    auth = {"Authorization": f"Bearer {token}"}

    # Upload requires auth.
    assert client.post("/api/genomes", files={"file": ("g.txt", _GENOME)}).status_code == 401

    up = client.post("/api/genomes", files={"file": ("g.txt", _GENOME)}, headers=auth)
    assert up.status_code == 201
    gid = up.json()["genome_id"]
    assert up.json()["markers"] == 2

    listing = client.get("/api/genomes", headers=auth).json()["genomes"]
    assert [g["id"] for g in listing] == [gid]

    traits = client.get(f"/api/genomes/{gid}/traits", headers=auth)
    assert traits.status_code == 200
    body = traits.json()
    assert body["filename"] == "g.txt"
    assert isinstance(body["traits"], list)   # rs4988235(A;A) is a known SNPedia trait
    assert all({"rsid", "genotype", "magnitude"} <= t.keys() for t in body["traits"])


def test_cannot_read_another_users_genome(tmp_path):
    client, _ = _client(tmp_path)
    client.post("/api/register", json={"username": "a", "password": "pw"})
    client.post("/api/register", json={"username": "b", "password": "pw"})
    ta = client.post("/api/login", json={"username": "a", "password": "pw"}).json()["token"]
    tb = client.post("/api/login", json={"username": "b", "password": "pw"}).json()["token"]

    gid = client.post(
        "/api/genomes", files={"file": ("g.txt", _GENOME)},
        headers={"Authorization": f"Bearer {ta}"},
    ).json()["genome_id"]

    # User b must not see user a's genome.
    r = client.get(f"/api/genomes/{gid}/traits", headers={"Authorization": f"Bearer {tb}"})
    assert r.status_code == 404


