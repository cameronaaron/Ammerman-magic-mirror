def test_share_endpoint_returns_png(tmp_path):
    import io

    from PIL import Image

    client, _ = _client(tmp_path)
    client.post("/api/register", json={"username": "ada", "password": "pw"})
    token = client.post("/api/login", json={"username": "ada", "password": "pw"}).json()["token"]
    auth = {"Authorization": f"Bearer {token}"}
    gid = client.post(
        "/api/genomes", files={"file": ("g.txt", _GENOME)}, headers=auth
    ).json()["genome_id"]

    photo = io.BytesIO()
    Image.new("RGB", (600, 800), (90, 120, 160)).save(photo, format="JPEG")
    r = client.post(
        f"/api/genomes/{gid}/share?fmt=square",
        files={"file": ("me.jpg", photo.getvalue(), "image/jpeg")},
        headers=auth,
    )
    assert r.status_code == 200
    assert r.headers["content-type"] == "image/png"
    out = Image.open(io.BytesIO(r.content))
    assert out.size == (1080, 1080)

    # Bad format is rejected.
    bad = client.post(
        f"/api/genomes/{gid}/share?fmt=nope",
        files={"file": ("me.jpg", photo.getvalue(), "image/jpeg")},
        headers=auth,
    )
    assert bad.status_code == 400
